function x = ch9_obs(e,w)
if nargin<2, w=1; end
q=3-w;j=min(e.g(:,w),4)+1;
c=e.gates(j,1:3);c2=e.gates(min(j+1,5),1:3);
x=[e.v(:,:,w)/7,(c-e.p(:,:,w))./[15 3 2],...
   (c2-e.p(:,:,w))./[25 3 2],(e.p(:,:,q)-e.p(:,:,w))./[8 3 2],...
   (e.v(:,:,q)-e.v(:,:,w))/7,e.g(:,w)/5,e.g(:,q)/5,...
   (e.c.time_limit-e.t)/e.c.time_limit,e.prev(:,:,w),...
   (e.gates(j,4)/2-e.c.gate_margin)/2,e.gates(j,5)/2-e.c.gate_margin,e.p(:,2,w)/5];
x=min(5,max(-5,x));
assert(size(x,2)==24,'Observation dimension is inconsistent.');
end
